<?php

namespace App\Domain\Marketing\Seo;

use App\Domain\PlatformSettings\PlatformSettings;

/**
 * robots.txt generation, validation and the safe editor.
 *
 * A generated default is served unless the operator supplies their own content, so a
 * deleted or broken custom file can never leave the site pointing crawlers at
 * nothing. Validation refuses the mistakes that actually hurt: an unknown directive,
 * a blanket disallow that also excludes the sitemap, and a relative sitemap URL.
 */
class RobotsService
{
    public const CONTENT_KEY = 'seo.robots_content';

    public const ENABLED_KEY = 'seo.robots_enabled';

    /** Directives we accept. Anything else is reported rather than silently kept. */
    public const ALLOWED_DIRECTIVES = [
        'user-agent', 'allow', 'disallow', 'sitemap', 'crawl-delay', 'host', 'clean-param',
    ];

    public function __construct(protected PlatformSettings $settings) {}

    public function enabled(): bool
    {
        return (bool) $this->settings->get(self::ENABLED_KEY, true);
    }

    public function isCustom(): bool
    {
        return trim((string) ($this->settings->get(self::CONTENT_KEY) ?? '')) !== '';
    }

    public function content(): string
    {
        $custom = trim((string) ($this->settings->get(self::CONTENT_KEY) ?? ''));

        return $custom !== '' ? $custom."\n" : $this->defaultContent();
    }

    /**
     * What the site serves when nothing has been customised.
     *
     * The private prefixes are the ones that actually exist: the platform workspace,
     * the tenant app, POS and kitchen screens, QR dining, payment callbacks, webhooks,
     * health and invitations. `/qr/` and `/payments/` were missing from the static file
     * this replaces.
     */
    public function defaultContent(): string
    {
        $lines = [
            '# Generated by the Marketing & Growth Center. Edit it under SEO → Sitemap & Robots.',
            'User-agent: *',
            'Allow: /',
            '',
            'Disallow: /platform',
            'Disallow: /dashboard',
            'Disallow: /pos',
            'Disallow: /qr/',
            'Disallow: /payments/',
            'Disallow: /webhooks/',
            'Disallow: /health',
            'Disallow: /up',
            'Disallow: /invitations/',
            'Disallow: /profile',
            'Disallow: /onboarding/',
            'Disallow: /login',
            'Disallow: /register',
            'Disallow: /forgot-password',
            'Disallow: /reset-password',
            'Disallow: /verify-email',
            'Disallow: /marketing/',
            '',
        ];

        if ($this->settings->get('seo.sitemap_enabled', true)) {
            $lines[] = 'Sitemap: '.$this->sitemapUrl();
            $lines[] = '';
        }

        return implode("\n", $lines);
    }

    /**
     * @return array{errors: list<string>, warnings: list<string>}
     */
    public function validate(string $content): array
    {
        $errors = [];
        $warnings = [];
        $userAgents = 0;
        $disallowAll = false;
        $allowAll = false;

        foreach (preg_split('/\R/', $content) ?: [] as $index => $rawLine) {
            $line = trim($rawLine);

            if ($line === '' || str_starts_with($line, '#')) {
                continue;
            }

            if (! str_contains($line, ':')) {
                $errors[] = 'Line '.($index + 1).': "'.$line.'" is not a directive (expected something like "Disallow: /path").';

                continue;
            }

            [$directive, $value] = array_map('trim', explode(':', $line, 2));
            $lower = strtolower($directive);

            if (! in_array($lower, self::ALLOWED_DIRECTIVES, true)) {
                $errors[] = 'Line '.($index + 1).': "'.$directive.'" is not a recognised robots directive.';
            }

            if ($lower === 'user-agent') {
                $userAgents++;
            }

            if ($lower === 'disallow' && $value === '/') {
                $disallowAll = true;
            }

            if ($lower === 'allow' && ($value === '/' || $value === '')) {
                $allowAll = true;
            }

            if ($lower === 'sitemap' && preg_match('#^https?://#i', $value) !== 1) {
                $errors[] = 'Line '.($index + 1).': the Sitemap must be an absolute http(s) URL.';
            }
        }

        if ($userAgents === 0) {
            $errors[] = 'A robots.txt must contain at least one "User-agent:" line.';
        }

        if ($disallowAll && $allowAll) {
            $warnings[] = '"Disallow: /" together with "Allow: /" means the whole site is blocked and then re-allowed. It is almost never what you intend.';
        }

        if (! $this->settings->get('seo.sitemap_enabled', true) && str_contains(strtolower($content), 'sitemap:')) {
            $warnings[] = 'This file advertises a sitemap, but sitemap generation is switched off, so that URL will 404.';
        }

        return ['errors' => $errors, 'warnings' => $warnings];
    }

    public function save(?string $content): void
    {
        $content = trim((string) $content);

        $this->settings->set(
            self::CONTENT_KEY,
            $content === '' ? null : $content,
            'seo',
        );
    }

    public function sitemapUrl(): string
    {
        return app(SitemapService::class)->host().'/sitemap.xml';
    }
}
